using System.Text;
using Umbraco.Cms.Infrastructure.ModelsBuilder.Building;

namespace Umbraco.Community.ModelAliases;

/// <summary>
/// Turns Models Builder's type models into one source file per model, each extending that model's
/// partial class with a nested <c>Aliases</c> class of property-alias constants. Pure: no I/O.
/// </summary>
internal static class ModelAliasesWriter
{
    /// <summary>
    /// Deliberately not <c>.generated.cs</c>: <c>ModelsGenerator</c> deletes every <c>*.generated.cs</c> it did
    /// not write itself, so files with that ending would be removed on each run.
    /// </summary>
    public const string FileSuffix = ".Aliases.gen.cs";

    public const string ClassName = "Aliases";

    /// <summary>
    /// Builds the files, keyed by file name. Throws <see cref="InvalidOperationException"/> when a model's
    /// aliases cannot be expressed as unique constant names.
    /// </summary>
    public static IReadOnlyDictionary<string, string> Write(IEnumerable<TypeModel> typeModels, string modelsNamespace)
    {
        var files = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

        foreach (TypeModel typeModel in typeModels)
        {
            files[typeModel.ClrName + FileSuffix] = WriteFile(typeModel, modelsNamespace);
        }

        return files;
    }

    private static string WriteFile(TypeModel typeModel, string modelsNamespace)
    {
        IReadOnlyList<PropertyModel> properties = CollectProperties(typeModel);

        var sb = new StringBuilder();
        sb.Append("//------------------------------------------------------------------------------\n");
        sb.Append("// <auto-generated>\n");
        sb.Append("//   This code was generated by Umbraco.Community.ModelAliases.\n");
        sb.Append("//\n");
        sb.Append("//   Changes to this file will be lost if the code is regenerated.\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("//------------------------------------------------------------------------------\n");
        sb.Append('\n');
        sb.Append("namespace ").Append(modelsNamespace).Append('\n');
        sb.Append("{\n");
        sb.Append("\tpublic partial class ").Append(typeModel.ClrName).Append('\n');
        sb.Append("\t{\n");
        sb.Append("#pragma warning disable 0109 // new is redundant\n");
        sb.Append("\t\t/// <summary>Property aliases of <see cref=\"").Append(typeModel.ClrName)
            .Append("\"/>, including those from its compositions and base types.</summary>\n");
        sb.Append("\t\tpublic new static class ").Append(ClassName).Append('\n');
        sb.Append("\t\t{\n");

        foreach (PropertyModel property in properties)
        {
            sb.Append("\t\t\tpublic const string ").Append(property.ClrName)
                .Append(" = \"").Append(Escape(property.Alias)).Append("\";\n");
        }

        sb.Append("\t\t}\n");
        sb.Append("#pragma warning restore 0109\n");
        sb.Append("\t}\n");
        sb.Append("}\n");

        return sb.ToString();
    }

    /// <summary>
    /// Everything the generated class exposes. <see cref="TypeModel.Properties"/> holds only a type's own
    /// properties, but the class also implements its compositions' properties and inherits its base
    /// types', and a nested class is not inherited in any useful way, so all of them are gathered here.
    /// </summary>
    private static IReadOnlyList<PropertyModel> CollectProperties(TypeModel typeModel)
    {
        var visited = new HashSet<TypeModel>();
        var byAlias = new Dictionary<string, PropertyModel>(StringComparer.Ordinal);
        Visit(typeModel);

        List<PropertyModel> properties = byAlias.Values
            .OrderBy(x => x.ClrName, StringComparer.Ordinal)
            .ToList();

        foreach (PropertyModel property in properties)
        {
            if (property.ClrName == ClassName)
            {
                throw new InvalidOperationException(
                    $"The property with alias \"{property.Alias}\" is named \"{property.ClrName}\" on the model for type \"{typeModel.Alias}\"."
                    + $" CSharp does not support a member named like its enclosing class, and Umbraco.Community.ModelAliases nests its constants in a class called \"{ClassName}\"."
                    + " Consider using an attribute to assign a different name to the property.");
            }
        }

        foreach (IGrouping<string, PropertyModel> clash in properties.GroupBy(x => x.ClrName).Where(x => x.Count() > 1))
        {
            throw new InvalidOperationException(
                $"Property name \"{clash.Key}\" on the model for type \"{typeModel.Alias}\" is used"
                + $" for properties with alias {string.Join(", ", clash.Select(x => "\"" + x.Alias + "\""))}, coming from its base types or compositions. Names have to be unique."
                + " Consider using an attribute to assign different names to conflicting properties.");
        }

        return properties;

        void Visit(TypeModel type)
        {
            if (!visited.Add(type))
            {
                return;
            }

            foreach (PropertyModel property in type.Properties)
            {
                // Not generated by Models Builder either, so there is no instance property to name.
                if (property.Errors is null)
                {
                    byAlias.TryAdd(property.Alias, property);
                }
            }

            if (type.BaseType is not null)
            {
                Visit(type.BaseType);
            }

            foreach (TypeModel mixin in type.MixinTypes)
            {
                Visit(mixin);
            }
        }
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
